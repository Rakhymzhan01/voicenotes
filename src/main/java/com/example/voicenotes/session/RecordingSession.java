package com.example.voicenotes.session;

import com.example.voicenotes.common.InvalidStateException;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.time.Instant;
import java.util.UUID;

/**
 * One recording (screen + voice) that becomes one structured note.
 *
 * <p>Status changes only through the methods below, so an invalid transition
 * (e.g. adding a chunk to a COMPLETED session) is impossible from any caller.
 *
 * <p>There is deliberately no {@code @OneToMany List<Chunk>} here: a session can
 * have hundreds of chunks, and a collection would invite loading all of them
 * by accident. Chunks are queried through {@code ChunkRepository} instead.
 */
@Entity
@Table(name = "recording_session")
public class RecordingSession {

    // Generated by Hibernate on persist. Assigning it ourselves would make Spring Data
    // treat the entity as existing and run merge() = an extra SELECT before INSERT.
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(nullable = false, length = 200)
    private String title;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private Language language;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private SessionStatus status;

    /** Optimistic locking: concurrent updates of the same row fail instead of silently overwriting. */
    @Version
    private long version;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected RecordingSession() {
        // for JPA
    }

    public RecordingSession(String title, Language language) {
        this.title = title;
        this.language = language;
        this.status = SessionStatus.CREATED;
    }

    public void rename(String newTitle) {
        this.title = newTitle;
    }

    public void changeLanguage(Language newLanguage) {
        if (status != SessionStatus.CREATED && status != SessionStatus.UPLOADING) {
            throw new InvalidStateException("Language can't be changed once processing has started (status " + status + ")");
        }
        this.language = newLanguage;
    }

    /** Called when a chunk is accepted. */
    public void onChunkUploaded() {
        switch (status) {
            case CREATED -> status = SessionStatus.UPLOADING;
            case UPLOADING -> { /* stays */ }
            default -> throw new InvalidStateException("Session is " + status + ", chunks are no longer accepted");
        }
    }

    /** Client says the recording is over; the processing pipeline can start. */
    public void finishUpload() {
        if (status != SessionStatus.UPLOADING) {
            throw new InvalidStateException("Only an UPLOADING session can be finished (status " + status + ")");
        }
        status = SessionStatus.PROCESSING;
    }

    public UUID getId() { return id; }
    public String getTitle() { return title; }
    public Language getLanguage() { return language; }
    public SessionStatus getStatus() { return status; }
    public long getVersion() { return version; }
    public Instant getCreatedAt() { return createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
}
