package com.example.voicenotes.chunk;

import com.example.voicenotes.chunk.dto.ChunkResponse;
import com.example.voicenotes.chunk.dto.CreateChunkRequest;
import com.example.voicenotes.common.PageResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.util.UUID;

@Tag(name = "Chunks", description = "Pieces of a recording uploaded while it is in progress")
@RestController
@RequestMapping("/api/sessions/{sessionId}/chunks")
public class ChunkController {

    private final ChunkService service;

    public ChunkController(ChunkService service) {
        this.service = service;
    }

    @Operation(summary = "Register an uploaded chunk",
            description = "201 on first upload, 200 when the same Idempotency-Key is retried with the same body, "
                    + "409 if the key was used with a different body or the sequence number is taken.")
    @PostMapping
    public ResponseEntity<ChunkResponse> upload(
            @PathVariable UUID sessionId,
            @Parameter(description = "Unique per chunk, generated by the client (e.g. a UUID). Reuse it on retry.")
            @RequestHeader("Idempotency-Key") @NotBlank @Size(max = 100) String idempotencyKey,
            @Valid @RequestBody CreateChunkRequest req) {
        ChunkService.UploadResult result = service.upload(sessionId, idempotencyKey, req);
        return ResponseEntity.status(result.created() ? HttpStatus.CREATED : HttpStatus.OK).body(result.chunk());
    }

    @Operation(summary = "List chunks of a session in recording order")
    @GetMapping
    public PageResponse<ChunkResponse> list(
            @PathVariable UUID sessionId,
            @RequestParam(defaultValue = "0") @Min(0) int page,
            @RequestParam(defaultValue = "50") @Min(1) @Max(200) int size) {
        return service.list(sessionId, page, size);
    }
}
