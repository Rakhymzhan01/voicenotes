package com.example.voicenotes.chunk;

import com.example.voicenotes.session.RecordingSession;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.FetchType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;
import java.util.UUID;

/**
 * Metadata of one uploaded piece of a recording. The bytes themselves will live
 * in object storage (S3/MinIO) later; week 1 stores only metadata.
 */
@Entity
@Table(name = "chunk")
public class Chunk {

    // Generated by Hibernate on persist. Assigning it ourselves would make Spring Data
    // treat the entity as existing and run merge() = an extra SELECT before INSERT.
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /**
     * LAZY: loading a chunk must not pull its session. The default for
     * {@code @ManyToOne} is EAGER, which is a classic source of extra queries.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "session_id", nullable = false, updatable = false)
    private RecordingSession session;

    @Column(name = "sequence_number", nullable = false, updatable = false)
    private int sequenceNumber;

    @Column(name = "idempotency_key", nullable = false, updatable = false, length = 100)
    private String idempotencyKey;

    @Column(name = "duration_ms", nullable = false)
    private int durationMs;

    @Column(name = "size_bytes", nullable = false)
    private long sizeBytes;

    @Column(name = "content_type", nullable = false, length = 100)
    private String contentType;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private ChunkStatus status;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    protected Chunk() {
        // for JPA
    }

    public Chunk(RecordingSession session, int sequenceNumber, String idempotencyKey,
                 int durationMs, long sizeBytes, String contentType) {
        this.session = session;
        this.sequenceNumber = sequenceNumber;
        this.idempotencyKey = idempotencyKey;
        this.durationMs = durationMs;
        this.sizeBytes = sizeBytes;
        this.contentType = contentType;
        this.status = ChunkStatus.UPLOADED;
    }

    public UUID getId() { return id; }
    public RecordingSession getSession() { return session; }
    public int getSequenceNumber() { return sequenceNumber; }
    public String getIdempotencyKey() { return idempotencyKey; }
    public int getDurationMs() { return durationMs; }
    public long getSizeBytes() { return sizeBytes; }
    public String getContentType() { return contentType; }
    public ChunkStatus getStatus() { return status; }
    public Instant getCreatedAt() { return createdAt; }
}
